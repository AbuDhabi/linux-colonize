/* Original game font uses three green shades; index 0 is transparent. */
static const uint8_t FF_COLOR_MAP[4] = {0, 0x0F, 0x07, 0x08};

static void put_pixel(ColonizeFramebuffer8* fb, int x, int y, uint8_t color) {
  if (!fb || !fb->pixels || x < 0 || y < 0 || x >= fb->width || y >= fb->height) {
    return;
  }
  fb->pixels[y * fb->width + x] = color;
}

static void draw_ff_glyph(
  const ColonizeFont* font,
  ColonizeFramebuffer8* framebuffer,
  int x,
  int y,
  unsigned char ch,
  uint8_t color
) {
  if (ch >= 128 || font->char_widths[ch] == 0) {
    return;
  }

  const int width = font->char_widths[ch];
  const int height = font->max_height;
  size_t pos = font->char_offsets[ch];
  if (pos >= font->section_size) {
    return;
  }

  for (int row = 0; row < height; ++row) {
    int col = 0;
    while (col < width) {
      if (pos >= font->section_size) {
        return;
      }
      const uint8_t byte = font->section_data[pos++];
      for (int shift = 6; shift >= 0; shift -= 2) {
        const uint8_t shade = (uint8_t)((byte >> shift) & 0x03u);
        if (shade != 0) {
          const uint8_t pixel = (color == 15 || color == 7) ? FF_COLOR_MAP[shade] : color;
          put_pixel(framebuffer, x + col, y + row, pixel);
        }
        col += 1;
        if (col >= width) {
          break;
        }
      }
    }
  }
}

static void draw_builtin_glyph(
  ColonizeFramebuffer8* framebuffer,
  int x,
  int y,
  unsigned char ch,
  uint8_t color
) {
  if (ch < 32 || ch > 126) {
    ch = '?';
  }
  const uint8_t* glyph = FONT5X7[ch - 32];
  for (int col = 0; col < 5; ++col) {
    uint8_t bits = glyph[col];
    for (int row = 0; row < 7; ++row) {
      if (bits & (1u << row)) {
        put_pixel(framebuffer, x + col, y + row, color);
      }
    }
  }
}

int font_text_width(const ColonizeFont* font, const char* text) {
  if (!text) {
    return 0;
  }
  int width = 0;
  for (const char* p = text; *p; ++p) {
    unsigned char ch = (unsigned char)*p;
    if (ch == '\n') {
      break;
    }
    if (ch == '~' || ch == '#') {
      continue;
    }
    if (font && font->section_data && ch < 128 && font->char_widths[ch] != 0) {
      width += font->char_widths[ch];
    } else {
      width += 6;
    }
  }
  return width;
}

bool font_glyph_ink_bounds(
  const ColonizeFont* font,
  unsigned char ch,
  int* out_min_x,
  int* out_min_y,
  int* out_max_x,
  int* out_max_y
) {
  if (!out_min_x || !out_min_y || !out_max_x || !out_max_y) {
    return false;
  }
  int min_x = 0;
  int min_y = 0;
  int max_x = -1;
  int max_y = -1;
  bool any = false;

  if (font && font->section_data && ch < 128 && font->char_widths[ch] != 0) {
    const int width = font->char_widths[ch];
    const int height = font->max_height;
    size_t pos = font->char_offsets[ch];
    min_x = width;
    min_y = height;
    for (int row = 0; row < height; ++row) {
      int col = 0;
      while (col < width) {
        if (pos >= font->section_size) {
          break;
        }
        const uint8_t byte = font->section_data[pos++];
        for (int shift = 6; shift >= 0; shift -= 2) {
          const uint8_t shade = (uint8_t)((byte >> shift) & 0x03u);
          if (shade != 0) {
            if (col < min_x) {
              min_x = col;
            }
            if (col > max_x) {
              max_x = col;
            }
            if (row < min_y) {
              min_y = row;
            }
            if (row > max_y) {
              max_y = row;
            }
            any = true;
          }
          col += 1;
          if (col >= width) {
            break;
          }
        }
      }
    }
  } else {
    if (ch < 32 || ch > 126) {
      ch = '?';
    }
    const uint8_t* glyph = FONT5X7[ch - 32];
    min_x = 5;
    min_y = 7;
    for (int col = 0; col < 5; ++col) {
      uint8_t bits = glyph[col];
      for (int row = 0; row < 7; ++row) {
        if (bits & (1u << row)) {
          if (col < min_x) {
            min_x = col;
          }
          if (col > max_x) {
            max_x = col;
          }
          if (row < min_y) {
            min_y = row;
          }
          if (row > max_y) {
            max_y = row;
          }
          any = true;
        }
      }
    }
  }

  if (!any) {
    return false;
  }
  *out_min_x = min_x;
  *out_min_y = min_y;
  *out_max_x = max_x;
  *out_max_y = max_y;
  return true;
}

void font_draw_text(
  const ColonizeFont* font,
  ColonizeFramebuffer8* framebuffer,
  int x,
  int y,
  const char* text,
  uint8_t color
) {
  font_draw_text_hotkey(font, framebuffer, x, y, text, color, color);
}

void font_draw_text_hotkey(
  const ColonizeFont* font,
  ColonizeFramebuffer8* framebuffer,
  int x,
  int y,
  const char* text,
  uint8_t color,
  uint8_t hotkey_color
) {
  if (!framebuffer || !text) {
    return;
  }

  const int line_step = font ? (font->max_height + 2) : 8;
  int cx = x;
  bool next_hotkey = false;
  for (const char* p = text; *p; ++p) {
    unsigned char ch = (unsigned char)*p;
    if (ch == '\n') {
      y += line_step;
      cx = x;
      next_hotkey = false;
      continue;
    }
    if (ch == '~') {
      next_hotkey = true;
      continue;
    }
    if (ch == '#') {
      continue;
    }

    const uint8_t use = next_hotkey ? hotkey_color : color;
    next_hotkey = false;

    /* Some .FF faces (notably FONTSMAL) omit punctuation such as '/'.
     * Skipping those glyphs advanced 0px and jammed digits into "57" for "5/7". */
    if (font && font->section_data && ch < 128 && font->char_widths[ch] != 0) {
      draw_ff_glyph(font, framebuffer, cx, y, ch, use);
      cx += font->char_widths[ch];
      continue;
    }

    if (ch < 32 || ch > 126) {
      ch = '?';
    }
    draw_builtin_glyph(framebuffer, cx, y, ch, use);
    cx += 6;
  }
}
